-- ============================================================
-- 10. HELPER FUNCTION - ADMIN CHECK
-- ============================================================

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1
        from public.profiles
        where id = auth.uid()
        and role = 'admin'
    );
$$;


-- ============================================================
-- 11. ENQUIRIES POLICIES
-- - Anyone (anonymous / authenticated) can SUBMIT enquiries
-- - Only Admins can VIEW and MANAGE enquiries
-- ============================================================

drop policy if exists "Anyone can submit enquiry" on public.enquiries;
create policy "Anyone can submit enquiry"
on public.enquiries
for insert
to anon, authenticated
with check (true);

drop policy if exists "Admins can view and manage enquiries" on public.enquiries;
create policy "Admins can view and manage enquiries"
on public.enquiries
for all
to authenticated
using (public.is_admin())
with check (public.is_admin());


-- ============================================================
-- 12. PROFILE POLICIES
-- ============================================================

drop policy if exists "Users can view own profile" on public.profiles;
create policy "Users can view own profile"
on public.profiles
for select
to authenticated
using (id = auth.uid() or public.is_admin());

drop policy if exists "Users can update own profile" on public.profiles;
create policy "Users can update own profile"
on public.profiles
for update
to authenticated
using (id = auth.uid())
with check (id = auth.uid());


